export type WriterSourceType = "existing" | "topic";
export type WriterContentCategory = "맛집" | "정책정보" | "기타";

export interface WriterPromptInput {
  sourceType: WriterSourceType;
  category: WriterContentCategory;
  title?: string;
  content: string;
  verifiedFacts?: string[];
  relatedPosts?: Array<{ title: string; url?: string }>;
}

function formatList(items: string[] | undefined, emptyText: string): string {
  return items?.length ? items.map((item) => `- ${item}`).join("\n") : emptyText;
}

function formatRelatedPosts(posts: WriterPromptInput["relatedPosts"]): string {
  if (!posts?.length) return "제공되지 않음. 제목이나 URL을 창작하지 말고 자리표시자로 남길 것.";
  return posts.map((post) => `- ${post.title}${post.url ? `: ${post.url}` : ""}`).join("\n");
}

